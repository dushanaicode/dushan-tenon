export function createKitTestI18n(language = "zh-CN"): i18n {
  const instance = createInstance();
  void instance.init({
    lng: language,
    fallbackLng: false,
    initAsync: false,
    keySeparator: false,
    resources: structuredClone(resources),
    interpolation: { escapeValue: false },
  });
  return instance;
}

export function withKitI18n(
  children: ReactNode,
  instance = createKitTestI18n(),
) {
  return <I18nextProvider i18n={instance}>{children}</I18nextProvider>;
}
